# Test frames for tb_secure_tx.sv: plain frames from the TX sources in, expected secure (or plain) frames out.
import struct, sys
from cryptography.hazmat.primitives.ciphers.aead import AESCCM
KEY = bytes(range(16))
def crc8(b):
    c = 0
    for x in b:
        c ^= x
        for _ in range(8): c = ((c << 1) ^ 0x07) & 0xFF if c & 0x80 else (c << 1) & 0xFF
    return c
def uart(body): return bytes([0xAA, 0x55, len(body)]) + body + bytes([crc8(bytes([len(body)]) + body)])
def sec_dl(ctr, payload):
    hdr = bytes([0x51]) + struct.pack('<II', 0xFFFFFFFE, ctr)
    return hdr + AESCCM(KEY, tag_length=4).encrypt(struct.pack('<II', 0xFFFFFFFE, ctr) + bytes([1]) + bytes(4), payload, hdr)
def rec(addr, seq, lat, lon, fl=0): return struct.pack('<HBiiB', addr, seq, lat, lon, fl)
table = bytes([0xD1, 2]) + rec(0x8101, 7, 410082000, 289784000) + rec(0x8203, 9, 410100000, 289800000, 2)
table16 = bytes([0xD1, 16]) + b''.join(rec(0x8100 + i, i, 410000000 + i, 289000000 - i) for i in range(16))
c3 = bytes([0xC3, 0xFE, 0xFF, 0xFF, 0xFF, 0x12, 1]) + bytes(8)
a2 = bytes([0xA2, 0xFE, 0xFF, 0xFF, 0xFF, 0x05]) + struct.pack('<I', 0xCAFE0001) + struct.pack('<H', 0x8301) + bytes([3, 1, 0])
assert len(c3) == 15 and len(a2) == 15
T = []   # (name, secure_en, ctr_load (-1 none), in, out)
T.append(('table N=2, ctr 1000, tx_repeat 1', 1, 1000, uart(table), uart(bytes([1]) + sec_dl(1000, table))))
T.append(('C3 admin, ctr 1001, tx_repeat 3', 1, -1, uart(c3), uart(bytes([3]) + sec_dl(1001, c3))))
T.append(('A2 join answer, ctr 1002', 1, -1, uart(a2), uart(bytes([3]) + sec_dl(1002, a2))))
T.append(('table N=16 (207 B secure), ctr 1003', 1, -1, uart(table16), uart(bytes([1]) + sec_dl(1003, table16))))
T.append(('secure_en=0: table unchanged', 0, -1, uart(table), uart(table)))
T.append(('secure_en=0: C3 unchanged', 0, -1, uart(c3), uart(c3)))
T.append(('back on, ctr continues at 1004', 1, -1, uart(c3), uart(bytes([3]) + sec_dl(1004, c3))))
T.append(('ctr_load 0xFFFFFFF0 (boot restore)', 1, 0xFFFFFFF0, uart(a2), uart(bytes([3]) + sec_dl(0xFFFFFFF0, a2))))
# node firmware V1.16.0 golden frames 7 and 8: the output must match them byte for byte
g7 = bytes.fromhex('AA551D0351FEFFFFFFF4010000CCB0B2BF875E74575BF013931D9BF639869BE268')
g8 = bytes.fromhex('AA55280151FEFFFFFF6400000088458DA1949364331AF8FCF2FEA420D8CEC93BACC7924A95DEE8FB5BE9660F')
a2g = bytes.fromhex('A2FEFFFFFF30A36017AD0281010200')
tbg = bytes.fromhex('D102641703111111111111111101028309111111111111111101')
assert uart(bytes([3]) + sec_dl(500, a2g)) == g7 and uart(bytes([1]) + sec_dl(100, tbg)) == g8
T.append(('GOLDEN 7: A2 ctr 500 (firmware V1.16.0)', 1, 500, uart(a2g), g7))
T.append(('GOLDEN 8: table ctr 100 (firmware)', 1, 100, uart(tbg), g8))
out = ['// generated by gen_stx.py - do not edit', f'localparam NT = {len(T)};',
       'reg [7:0] TI [0:NT-1][0:255]; reg [7:0] TO [0:NT-1][0:255]; integer TIN [0:NT-1], TON [0:NT-1];',
       'reg TEN [0:NT-1]; reg TLD [0:NT-1]; reg [31:0] TCV [0:NT-1]; reg [8*40-1:0] TNAME [0:NT-1];', 'initial begin']
for i, (nm, en, ld, ib, ob) in enumerate(T):
    out.append(f'    TNAME[{i}] = "{nm}"; TEN[{i}] = {en}; TLD[{i}] = {int(ld >= 0)}; TCV[{i}] = 32\'h{max(ld,0):08x}; TIN[{i}] = {len(ib)}; TON[{i}] = {len(ob)};')
    out.append('    ' + ' '.join(f"TI[{i}][{j}] = 8'h{b:02x};" for j, b in enumerate(ib)))
    out.append('    ' + ' '.join(f"TO[{i}][{j}] = 8'h{b:02x};" for j, b in enumerate(ob)))
out.append('end')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')
print(len(T), 'tests; table16 secure frame', len(T[3][4]), 'bytes')
