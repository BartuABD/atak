"""mkfont.py - renders monospace fonts into a C header of 8-bit alpha glyphs for atak_gui (no font library on the board).

    python mkfont.py ../font.h

Glyphs: ASCII 32..126, then index 95 = the copyright sign. Each font is a fixed cell (w x h); glyph g of font f
starts at f.bits[g * w * h], one byte per pixel (0 = background, 255 = full ink).
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONTS = [  # C name, TTF, pixel size
    ("font_s", "C:/Windows/Fonts/consola.ttf", 14),
    ("font_b", "C:/Windows/Fonts/consolab.ttf", 15),
    ("font_l", "C:/Windows/Fonts/consolab.ttf", 20),
]
CHARS = [chr(c) for c in range(32, 127)] + ["\u00a9"]


def render(name, path, size):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    w = round(f.getlength("M"))
    h = asc + desc
    data = bytearray()
    for ch in CHARS:
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255)
        data += im.tobytes()
    lines = [f"static const unsigned char {name}_bits[{len(data)}] = {{"]
    for i in range(0, len(data), 32):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
    lines.append("};")
    lines.append(f"static const struct font {name} = {{ {w}, {h}, {name}_bits }};")
    return "\n".join(lines)


def main():
    out = [
        "/* font.h - generated by tools/mkfont.py from Consolas (Windows fonts). Do not edit. */",
        "#ifndef FONT_H",
        "#define FONT_H",
        "struct font { int w, h; const unsigned char *bits; };   /* glyph g at bits[g*w*h], g = char-32, 95 = (c) */",
    ]
    for name, path, size in FONTS:
        out.append(render(name, path, size))
    out.append("#endif")
    with open(sys.argv[1], "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
