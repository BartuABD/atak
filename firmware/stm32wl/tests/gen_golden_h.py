#!/usr/bin/env python3
"""Reads docs/protocol/golden/golden_frames.json and writes a C header for test_golden.c.
usage: gen_golden_h.py <golden_frames.json> <out.h>"""
import json, sys

def arr(hexs):
    b = bytes.fromhex(hexs)
    return '{' + ','.join('0x%02x' % x for x in b) + '}', len(b)

d = json.load(open(sys.argv[1]))
rows = []
def add(name, direction, air, pt, uart=None):
    a, al = arr(air); p, pl = arr(pt)
    u, ul = arr(uart) if uart else ('{0}', 0)
    rows.append('  { "%s", %d, %s, %d, %s, %d, %s, %d },' % (name, direction, a, al, p, pl, u, ul))
for f in d['frames']:
    dirn = 0 if f['direction'] == 'node_to_zybo' else 1
    add(f['name'], dirn, f['air_hex'], f['plaintext_hex'], f.get('uart_hex'))
    if 'inner' in f:
        add(f['name'] + '/inner', 0, f['inner']['air_hex'], f['inner']['plaintext_hex'])
key = ','.join('0x%02x' % x for x in bytes.fromhex(d['key_hex']))
with open(sys.argv[2], 'w') as o:
    o.write('/* generated by gen_golden_h.py from golden_frames.json - do not edit */\n')
    o.write('static const uint8_t GOLDEN_KEY[16] = {%s};\n' % key)
    o.write('typedef struct { const char *name; int dir; uint8_t air[96]; int airLen; uint8_t pt[64]; int ptLen; uint8_t uart[96]; int uartLen; } GoldenFrame_t;\n')
    o.write('static const GoldenFrame_t GOLDEN[] = {\n' + '\n'.join(rows) + '\n};\n')
    o.write('#define GOLDEN_N (sizeof(GOLDEN) / sizeof(GOLDEN[0]))\n')
